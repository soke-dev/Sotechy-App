// Draws the PNG art used in Sotechy emails (email apps don't show SVG) from the same illustrations as the
// dashboard. Writes to apps/api/public/email. Run again after changing an illustration:
//   node --import tsx scripts/email-art.tsx   (from apps/merchant)
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { renderToStaticMarkup } from "react-dom/server";
import sharp from "sharp";
import { Illo, Sparkle, type IlloName as DashboardIllo } from "../src/components/illustrations";

// The emails still use the sparkle, which the dashboard doesn't
type IlloName = DashboardIllo | "sparkle";

const here = __dirname;
const out = join(here, "../../api/public/email");
mkdirSync(out, { recursive: true });

const svgOf = (name: IlloName, size: number) => renderToStaticMarkup(name === "sparkle" ? <Sparkle size={size} /> : <Illo name={name} size={size} />);
/** An illustration's inner drawing, placed at x,y and scaled to `size` */
const place = (name: IlloName, x: number, y: number, size: number, rotate = 0) => {
  const inner = svgOf(name, size).replace(/^<svg[^>]*>/, "").replace(/<\/svg>$/, "");
  return `<g transform="translate(${x} ${y}) rotate(${rotate} ${size / 2} ${size / 2}) scale(${size / 48})">${inner}</g>`;
};

/** The soft scalloped badge from the app's welcome screen */
function badge(cx: number, cy: number, r: number, lobes = 14) {
  const pts: string[] = [];
  for (let i = 0; i < lobes; i++) {
    const a0 = (i / lobes) * Math.PI * 2;
    const a1 = ((i + 0.5) / lobes) * Math.PI * 2;
    const a2 = ((i + 1) / lobes) * Math.PI * 2;
    const p = (a: number, rr: number) => `${(cx + Math.cos(a) * rr).toFixed(1)} ${(cy + Math.sin(a) * rr).toFixed(1)}`;
    if (i === 0) pts.push(`M ${p(a0, r)}`);
    pts.push(`Q ${p(a1, r * 1.12)} ${p(a2, r)}`);
  }
  return `<path d="${pts.join(" ")} Z" fill="#FFE3B3"/>`;
}

/** Hero: main illustration on the badge, two small accents floating around it. 2× for sharp screens. */
async function hero(file: string, main: IlloName, accents: [IlloName, IlloName]) {
  const W = 560;
  const H = 300;
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}" viewBox="0 0 ${W} ${H}">
    ${badge(W / 2, H / 2, 112)}
    <circle cx="${W / 2}" cy="${H / 2}" r="78" fill="#FFF6E8"/>
    ${place(main, W / 2 - 64, H / 2 - 64, 128)}
    ${place(accents[0], 92, 44, 64, -12)}
    ${place(accents[1], W - 152, H - 112, 60, 10)}
    <circle cx="140" cy="${H - 70}" r="7" fill="#F7931E"/>
    <circle cx="${W - 120}" cy="62" r="5" fill="#FDB913"/>
    <circle cx="${W - 92}" cy="96" r="3.5" fill="#F0603F"/>
  </svg>`;
  await sharp(Buffer.from(svg)).png().toFile(join(out, file));
}

/** Small icon for detail rows, 2× */
const icon = (name: IlloName) => sharp(Buffer.from(`<svg xmlns="http://www.w3.org/2000/svg" ${svgOf(name, 96).slice(4)}`)).png().toFile(join(out, `icon-${name}.png`));

const HEROES: [string, IlloName, [IlloName, IlloName]][] = [
  ["welcome", "bag", ["heart", "sparkle"]],
  ["code", "shield", ["mail", "sparkle"]],
  ["paid", "receipt", ["coin", "sparkle"]],
  ["processing", "box", ["tag", "sparkle"]],
  ["ready", "store", ["pin", "sparkle"]],
  ["dispatched", "bike", ["pin", "sparkle"]],
  ["delivered", "home", ["heart", "sparkle"]],
  ["cancelled", "receipt", ["chat", "pin"]],
  ["refunded", "wallet", ["coin", "sparkle"]],
  ["offer", "tag", ["chat", "coin"]],
  ["offer-accepted", "tag", ["heart", "sparkle"]],
  ["store-notice", "chat", ["store", "heart"]],
  ["store-opened", "store", ["coin", "sparkle"]],
  ["new-order", "box", ["bike", "sparkle"]],
  ["payout", "bank", ["coin", "sparkle"]],
  ["verified", "shield", ["store", "sparkle"]],
  ["featured", "sparkle", ["store", "heart"]],
];
const ICONS: IlloName[] = ["pin", "bike", "store", "phone", "coin", "receipt", "box", "tag", "bank", "chat", "card", "wallet", "heart", "shield", "sparkle", "doc"];

async function main() {
  await Promise.all([...HEROES.map(([f, m, a]) => hero(`hero-${f}.png`, m, a)), ...ICONS.map(icon)]);
  await sharp(join(here, "../../../brand-assets/logo/light-logo-small.png")).toFile(join(out, "logo.png"));
  writeFileSync(join(out, "README.md"), "Generated by apps/merchant/scripts/email-art.tsx. Don't edit by hand.\n");
  console.log(`Wrote ${HEROES.length} heroes and ${ICONS.length} icons to ${out}`);
}
main();
