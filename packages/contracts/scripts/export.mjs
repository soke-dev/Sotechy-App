// Writes dist/index.ts from the forge build, so the API gets the ABIs, bytecode and deployments
// without needing forge on the server. Run by "pnpm build" and after every deploy.
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { readArtifact, readDeployments, ROOT } from "./lib.mjs";

const tokens = readArtifact("tokens");
const receipts = readArtifact("receipts");
// Local anvil tries never reach the API
const deployments = Object.fromEntries(
  Object.entries(readDeployments()).map(([contract, chains]) => [contract, Object.fromEntries(Object.entries(chains).filter(([chain]) => chain !== "local"))]),
);

const out = `// Generated by scripts/export.mjs from the forge build. Don't edit by hand.

export const sotechyTokensAbi = ${JSON.stringify(tokens.abi, null, 2)} as const;

export const sotechyTokensBytecode = "${tokens.bytecode}" as const;

export const sotechyReceiptsAbi = ${JSON.stringify(receipts.abi, null, 2)} as const;

export const sotechyReceiptsBytecode = "${receipts.bytecode}" as const;

export interface Deployment {
  chainId: number;
  address: \`0x\${string}\`;
  version: number;
  owner: \`0x\${string}\`;
  operator: \`0x\${string}\`;
  txHash: \`0x\${string}\`;
  block: number;
  deployedAt: string;
}

export type ContractName = "tokens" | "receipts";

/** Every deploy so far, by contract and chain name ("monad", "base", ...); the last one is current */
export const deployments: Record<ContractName, Record<string, Deployment[]>> = ${JSON.stringify(deployments, null, 2)};
`;

mkdirSync(join(ROOT, "dist"), { recursive: true });
writeFileSync(join(ROOT, "dist", "index.ts"), out);
const count = Object.values(deployments).reduce((n, chains) => n + Object.keys(chains).length, 0);
console.log(`dist/index.ts written (${count} live deployments)`);
