// Writes dist/index.ts from the forge build, so the API gets the ABI, bytecode and deployments
// without needing forge on the server. Run by "pnpm build" and after every deploy.
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { readArtifact, readDeployments, ROOT } from "./lib.mjs";

const { abi, bytecode } = readArtifact();
// Local anvil tries never reach the API
const deployments = Object.fromEntries(Object.entries(readDeployments()).filter(([name]) => name !== "local"));

const out = `// Generated by scripts/export.mjs from the forge build. Don't edit by hand.

export const sotechyTokensAbi = ${JSON.stringify(abi, null, 2)} as const;

export const sotechyTokensBytecode = "${bytecode}" as const;

export interface Deployment {
  chainId: number;
  address: \`0x\${string}\`;
  version: number;
  owner: \`0x\${string}\`;
  operator: \`0x\${string}\`;
  txHash: \`0x\${string}\`;
  block: number;
  deployedAt: string;
}

/** Every deploy so far, by chain name ("monad", "base", ...) */
export const deployments: Record<string, Deployment[]> = ${JSON.stringify(deployments, null, 2)};
`;

mkdirSync(join(ROOT, "dist"), { recursive: true });
writeFileSync(join(ROOT, "dist", "index.ts"), out);
console.log(`dist/index.ts written (${abi.length} ABI entries, ${Object.keys(deployments).length} chains deployed)`);
